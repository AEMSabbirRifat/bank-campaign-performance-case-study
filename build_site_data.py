"""Turns results/*.csv into results/site_data.ts, the data file the portfolio page reads.

Every number on the live case-study page comes from this file, so the page cannot drift from the SQL output.

Usage:  python build_site_data.py
"""
import csv
import json
import pathlib

HERE = pathlib.Path(__file__).parent
OUT = HERE / "results" / "site_data.ts"


def num(v):
    if v == "":
        return None
    try:
        f = float(v)
    except ValueError:
        return v
    return int(f) if f.is_integer() else f


tables = {}
for path in sorted((HERE / "results").glob("[0-9]*.csv")):
    with path.open(encoding="utf-8") as f:
        rows = [{k: num(v) for k, v in row.items()} for row in csv.DictReader(f)]
    key = "q" + path.stem.split("_", 1)[0]          # 01_market_overview -> q01
    tables[key] = rows

body = "// Generated by build_site_data.py - do not edit by hand.\n"
body += "// Source: Moro, S., Rita, P. & Cortez, P. (2014). Bank Marketing. UCI Machine Learning Repository, CC BY 4.0 (summary tables only).\n\n"
for key, rows in tables.items():
    body += f"export const {key} = {json.dumps(rows, ensure_ascii=False, indent=2)} as const;\n\n"
OUT.write_text(body, encoding="utf-8")
print(f"wrote {OUT} with {len(tables)} tables")
